// src/components/Legal/PrivacyPolicy.jsx — политика обработки персональных данных
// Реквизиты оператора подставляются из настроек (админка → Юридические данные).
import React, { useEffect, useState } from 'react';
import { supabase } from '../../lib/supabase';
import './legal.scss';

const FALLBACK = {
  operator_name: '',
  operator_type: '',
  inn: '',
  ogrn: '',
  address: '',
  email: 'nixoffers@gmail.com',
  policy_version: ''
};

// Незаполненный реквизит показываем явно, а не прячем: пустая политика
// хуже, чем честно видимый пробел, который надо закрыть
const Value = ({ children }) =>
  children ? <>{children}</> : <span className="legal__todo">— не указано —</span>;

export default function PrivacyPolicy() {
  const [legal, setLegal] = useState(FALLBACK);

  useEffect(() => {
    supabase.from('site_settings').select('value').eq('key', 'legal').maybeSingle()
      .then(({ data }) => data?.value && setLegal({ ...FALLBACK, ...data.value }));
  }, []);

  const operator = [legal.operator_type, legal.operator_name].filter(Boolean).join(' ');

  return (
    <div className="legal">
      <div className="legal__inner">
        <a href="/" className="legal__back">← На главную</a>

        <h1 className="legal__title">Политика в отношении обработки персональных данных</h1>
        {legal.policy_version && (
          <p className="legal__meta">Редакция от {legal.policy_version}</p>
        )}

        <h2>1. Общие положения</h2>
        <p>
          Настоящая Политика определяет порядок обработки персональных данных
          посетителей сайта и меры по обеспечению их безопасности. Политика
          составлена в соответствии с Федеральным законом от 27.07.2006 № 152-ФЗ
          «О персональных данных».
        </p>
        <p>
          Оператор персональных данных: <b><Value>{operator}</Value></b>
          {legal.inn && <>, ИНН {legal.inn}</>}
          {legal.ogrn && <>, ОГРН{legal.operator_type === 'ИП' ? 'ИП' : ''} {legal.ogrn}</>}
          {legal.address && <>, адрес: {legal.address}</>}.
        </p>
        <p>
          Контакт для обращений по вопросам обработки персональных данных:{' '}
          <a href={`mailto:${legal.email}`}>{legal.email}</a>.
        </p>

        <h2>2. Какие данные обрабатываются</h2>
        <p>Оператор обрабатывает данные, которые вы указываете добровольно в форме обратной связи:</p>
        <ul>
          <li>имя;</li>
          <li>название компании;</li>
          <li>адрес электронной почты;</li>
          <li>тип обращения и текст сообщения.</li>
        </ul>
        <p>
          Дополнительно автоматически собираются обезличенные технические данные о
          посещениях: адрес открытой страницы, источник перехода и дата обращения.
          Эти данные не позволяют вас идентифицировать. IP-адреса и файлы cookie
          для целей отслеживания оператором не сохраняются.
        </p>
        <p>
          Сайт не предназначен для сбора данных несовершеннолетних, специальных
          категорий персональных данных и биометрических данных.
        </p>

        <h2>3. Цели обработки</h2>
        <ul>
          <li>рассмотрение обращений о сотрудничестве и обратная связь по ним;</li>
          <li>ведение переговоров и исполнение договорённостей;</li>
          <li>сбор обезличенной статистики для улучшения работы сайта.</li>
        </ul>

        <h2>4. Правовые основания</h2>
        <p>
          Обработка осуществляется на основании вашего согласия, которое вы даёте,
          отмечая соответствующий пункт при отправке формы, а также на основании
          законных интересов оператора по рассмотрению поступивших обращений.
        </p>

        <h2>5. Передача данных третьим лицам</h2>
        <p>
          Оператор не продаёт и не передаёт ваши данные третьим лицам для
          самостоятельных целей. Для работы сайта привлекаются поставщики услуг,
          обрабатывающие данные по поручению оператора:
        </p>
        <ul>
          <li>хостинг сайта и веб-аналитика — Vercel Inc.;</li>
          <li>база данных и хранение обращений — Supabase Inc. (серверы в ЕС);</li>
          <li>уведомления о новых обращениях — Telegram Messenger.</li>
        </ul>
        <p>
          Указанные сервисы могут обрабатывать данные за пределами Российской
          Федерации. Отправляя форму, вы соглашаетесь с таким трансграничным
          обменом данными.
        </p>

        <h2>6. Сроки хранения</h2>
        <p>
          Обращения хранятся до достижения целей обработки, но не дольше трёх лет с
          момента последнего взаимодействия, либо до отзыва согласия. Обезличенная
          статистика посещений хранится в агрегированном виде без ограничения срока.
        </p>

        <h2>7. Ваши права</h2>
        <p>Вы вправе:</p>
        <ul>
          <li>получить сведения об обработке ваших данных;</li>
          <li>требовать уточнения, блокирования или удаления данных;</li>
          <li>отозвать согласие на обработку в любой момент.</li>
        </ul>
        <p>
          Для этого направьте запрос на{' '}
          <a href={`mailto:${legal.email}`}>{legal.email}</a>. Ответ будет
          предоставлен в сроки, установленные законодательством.
        </p>

        <h2>8. Защита данных</h2>
        <p>
          Доступ к обращениям имеют только уполномоченные лица оператора. Передача
          данных выполняется по защищённому протоколу HTTPS, доступ к базе данных
          ограничен на уровне прав доступа.
        </p>

        <h2>9. Изменения политики</h2>
        <p>
          Оператор вправе изменять настоящую Политику. Актуальная редакция всегда
          доступна на этой странице.
        </p>
      </div>
    </div>
  );
}
